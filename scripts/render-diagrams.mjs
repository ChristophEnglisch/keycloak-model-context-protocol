#!/usr/bin/env node
/**
 * Renders docs/diagrams/*.mmd to SVG. npmjs.com does not render Mermaid, so the
 * README embeds the SVGs by absolute URL instead of Mermaid blocks. The SVGs are
 * not part of the npm package (see "files" in package.json).
 *
 * Usage:
 *   node scripts/render-diagrams.mjs           render every diagram
 *   node scripts/render-diagrams.mjs --check   exit 1 if an SVG is missing or stale,
 *                                              or the README embeds diagrams wrongly
 *
 * Rendering runs mermaid-cli through npx, so the first run downloads it and a
 * headless Chrome. --check renders nothing and needs no dependencies: each SVG
 * carries a stamp with a hash of its source, the shared config and the
 * mermaid-cli version, and --check compares that stamp. Comparing the SVG itself
 * would fail across machines, because fonts and Chrome versions change the output.
 */
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const MERMAID_CLI = "@mermaid-js/mermaid-cli@12.0.0";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = resolve(root, "docs/diagrams");
const configFile = resolve(dir, "mermaid.config.json");
const check = process.argv.includes("--check");

const stampPattern =
  /^<!-- Generated by scripts\/render-diagrams\.mjs from \S+\.mmd, do not edit\. hash: ([0-9a-f]{64}) -->\n/;
const stamp = (name, hash) =>
  `<!-- Generated by scripts/render-diagrams.mjs from ${name}.mmd, do not edit. hash: ${hash} -->\n`;

async function rawBaseUrl() {
  const pkg = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
  const repo = pkg.repository.url.match(/github\.com\/(.+?)(?:\.git)?$/)[1];
  return `https://raw.githubusercontent.com/${repo}/main/docs/diagrams/`;
}

async function sourceHash(name, config) {
  const source = await readFile(resolve(dir, `${name}.mmd`), "utf8");
  return createHash("sha256").update(`${MERMAID_CLI}\n${config}\n${source}`).digest("hex");
}

async function render(name, hash) {
  const svgFile = resolve(dir, `${name}.svg`);
  await promisify(execFile)(
    "npx",
    [
      "--yes",
      MERMAID_CLI,
      "--quiet",
      "-i",
      resolve(dir, `${name}.mmd`),
      "-o",
      svgFile,
      "-c",
      configFile,
      "-b",
      "white",
    ],
    { shell: process.platform === "win32" },
  );
  const svg = await readFile(svgFile, "utf8");
  await writeFile(svgFile, `${stamp(name, hash)}${svg.trimEnd()}\n`);
}

async function checkSvg(name, hash) {
  const svg = await readFile(resolve(dir, `${name}.svg`), "utf8").catch(() => null);
  if (svg === null) return `docs/diagrams/${name}.svg is missing.`;
  if (svg.match(stampPattern)?.[1] !== hash) return `docs/diagrams/${name}.svg is stale.`;
  return null;
}

async function checkReadme(names, base) {
  const readme = await readFile(resolve(root, "README.md"), "utf8");
  const problems = [];
  if (/^```mermaid/m.test(readme)) {
    problems.push(
      "README.md contains a Mermaid block. npm does not render it: move it to docs/diagrams/.",
    );
  }
  for (const [, url] of readme.matchAll(/\]\(([^)\s]*docs\/diagrams\/[^)\s]*)/g)) {
    const name = url.startsWith(base) && url.slice(base.length).match(/^([\w-]+)\.svg$/)?.[1];
    if (!name)
      problems.push(`README.md embeds ${url}. Use ${base}<name>.svg, relative links break on npm.`);
    else if (!names.includes(name))
      problems.push(`README.md embeds ${url}, but docs/diagrams/${name}.mmd does not exist.`);
  }
  return problems;
}

const files = await readdir(dir);
const names = files.filter((f) => f.endsWith(".mmd")).map((f) => f.slice(0, -4));
const config = await readFile(configFile, "utf8");

if (check) {
  const problems = [];
  for (const name of names) {
    const problem = await checkSvg(name, await sourceHash(name, config));
    if (problem) problems.push(problem);
  }
  for (const f of files.filter((f) => f.endsWith(".svg"))) {
    if (!names.includes(f.slice(0, -4))) problems.push(`docs/diagrams/${f} has no .mmd source.`);
  }
  problems.push(...(await checkReadme(names, await rawBaseUrl())));
  if (problems.length > 0) {
    for (const p of problems) console.error(p);
    console.error("Run `npm run docs:diagrams` and commit the result.");
    process.exit(1);
  }
  console.log(`${names.length} diagrams are up to date.`);
} else {
  for (const name of names) {
    const hash = await sourceHash(name, config);
    if ((await checkSvg(name, hash)) === null) {
      console.log(`docs/diagrams/${name}.svg is up to date.`);
      continue;
    }
    await render(name, hash);
    console.log(`Rendered docs/diagrams/${name}.svg.`);
  }
}
